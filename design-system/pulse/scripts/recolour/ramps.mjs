// Generates the accessible PULSE ramps. Each step is solved (in OKLCH) to a contrast target against white,
// so a step's number tells you what it can safely do:
//   500 = 3.5:1 (UI parts)   600 = 5.3:1 (AA text)   700 = 8.6:1 (AAA text)
// Run: node scripts/recolour/ramps.mjs   ->  writes figma-tokens/pulse-accessible-palette.json
import fs from 'fs';

const lin = c => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const gam = c => (c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055);
function oklch2rgb(L, C, hDeg) {
  const h = (hDeg * Math.PI) / 180;
  const a = C * Math.cos(h), b = C * Math.sin(h);
  const l_ = L + 0.3963377774 * a + 0.2158037573 * b;
  const m_ = L - 0.1055613458 * a - 0.0638541728 * b;
  const s_ = L - 0.0894841775 * a - 1.2914855480 * b;
  const l = l_ ** 3, m = m_ ** 3, s = s_ ** 3;
  return [4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s, -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s, -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s];
}
const inGamut = rgb => rgb.every(v => v >= -1e-6 && v <= 1 + 1e-6);
const clamp = v => Math.min(1, Math.max(0, v));
const toHex = rgb => '#' + rgb.map(v => Math.round(clamp(gam(clamp(v))) * 255).toString(16).padStart(2, '0')).join('');
function hexLum(hex) { const n = parseInt(hex.slice(1), 16); const [r, g, b] = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map(v => lin(v / 255)); return 0.2126 * r + 0.7152 * g + 0.0722 * b; }
export const ratio = (a, b) => { const x = hexLum(a), y = hexLum(b); return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05); };
const colourAt = (L, C, h) => { let c = C; while (c > 0 && !inGamut(oklch2rgb(L, c, h))) c -= 0.002; return toHex(oklch2rgb(L, Math.max(0, c), h)); };
const stepFor = (target, C, h) => { let lo = 0, hi = 1; for (let i = 0; i < 40; i++) { const mid = (lo + hi) / 2; ratio(colourAt(mid, C, h), '#ffffff') > target ? (lo = mid) : (hi = mid); } return colourAt((lo + hi) / 2, C, h); };

export const STEPS = { 50: 1.06, 100: 1.14, 200: 1.32, 300: 1.8, 400: 2.5, 500: 3.5, 600: 5.3, 700: 8.6, 800: 11.5, 900: 14.8, 950: 18.0 };
// Hue and chroma follow the original system: a muted navy brand, cool slate neutrals, familiar status hues.
export const FAMILIES = {
  blue:    { h: 262, c: 0.125 },
  neutral: { h: 255, c: 0.026 },
  red:     { h: 27,  c: 0.19 },
  amber:   { h: 80,  c: 0.14 },
  green:   { h: 154, c: 0.15 },
  teal:    { h: 190, c: 0.095 },
  cyan:    { h: 220, c: 0.11 },
  purple:  { h: 300, c: 0.17 },
};
const CHROMA_SCALE = { 50: 0.3, 100: 0.42, 200: 0.6, 300: 0.82 };

export function build() {
  const ramps = {};
  for (const [name, { h, c }] of Object.entries(FAMILIES)) {
    ramps[name] = {};
    for (const [step, target] of Object.entries(STEPS)) ramps[name][step] = stepFor(target, c * (CHROMA_SCALE[step] ?? 1), h);
  }
  return ramps;
}

if (import.meta.url === `file://${process.argv[1].replace(/\\/g, '/')}` || process.argv[1]?.endsWith('ramps.mjs')) {
  const ramps = build();
  const out = { $description: 'Accessible PULSE palette. Generated by scripts/recolour/ramps.mjs.', steps: STEPS, ramps };
  fs.writeFileSync('figma-tokens/pulse-accessible-palette.json', JSON.stringify(out, null, 2), 'utf8');
  for (const [f, s] of Object.entries(ramps)) console.log(f.padEnd(8), Object.entries(s).map(([k, v]) => `${k}:${v}`).join(' '));
  // Proof against the real WCAG thresholds (the solver aims a little above them, then hex rounding costs a few hundredths).
  const MIN = { 500: 3, 600: 4.5, 700: 7, 800: 10, 900: 13, 950: 16 };
  let bad = 0;
  for (const [f, s] of Object.entries(ramps)) for (const [k, minimum] of Object.entries(MIN)) if (ratio(s[k], '#ffffff') < minimum) { bad++; console.log('FAIL', f, k, s[k], ratio(s[k], '#ffffff').toFixed(2)); }
  console.log(bad ? `${bad} steps below their threshold` : 'every step clears its threshold: 500 >= 3:1, 600 >= 4.5:1, 700 >= 7:1');
}
