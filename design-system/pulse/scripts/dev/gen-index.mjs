/**
 * Regenerates src/components/index.ts from the exports of every src/components/<Folder>/*.ts(x) file.
 *   node scripts/dev/gen-index.mjs
 * Skips demos, _shared, and files that start with "_". Reports name clashes instead of silently shadowing.
 * Hand-maintained extras live in src/components/mui.ts (plain MUI primitives with no Pulse wrapper).
 */
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '../../src/components');
const values = new Map(); // name -> file
const types = new Map();
const clashes = [];
const lines = [];

const add = (map, name, file) => {
  if (map.has(name) && map.get(name) !== file) clashes.push(`${name}: ${map.get(name)} vs ${file}`);
  else map.set(name, file);
};

/** Components live in src/components/<category>/<Component>/<File>.tsx */
const componentDirs = [];
for (const cat of readdirSync(root).sort()) {
  const catDir = join(root, cat);
  if (!statSync(catDir).isDirectory() || cat.startsWith('_')) continue;
  for (const name of readdirSync(catDir).sort()) if (statSync(join(catDir, name)).isDirectory()) componentDirs.push([`${cat}/${name}`, join(catDir, name)]);
}
for (const [folder, dir] of componentDirs) {
  {
    for (const f of readdirSync(dir).sort()) {
    if (!/\.tsx?$/.test(f) || /\.demo\.tsx$/.test(f) || f.startsWith('_') || /\.stories\.tsx?$/.test(f) || f === 'Surfaces.tsx' || /^index\./.test(f)) continue;
    const src = readFileSync(join(dir, f), 'utf8');
    const rel = `./${folder}/${f.replace(/\.tsx?$/, '')}`;
    const v = new Set();
    const t = new Set();
    for (const m of src.matchAll(/^export\s+(?:declare\s+)?(?:async\s+)?(?:function\*?|const|let|class|enum)\s+([A-Za-z0-9_$]+)/gm)) v.add(m[1]);
    for (const m of src.matchAll(/^export\s+(?:declare\s+)?(?:interface|type)\s+([A-Za-z0-9_$]+)/gm)) t.add(m[1]);
    for (const m of src.matchAll(/^export\s+(type\s+)?\{([^}]+)\}(?!\s*from)/gms)) {
      for (const part of m[2].split(',')) {
        const p = part.trim();
        if (!p) continue;
        const isType = Boolean(m[1]) || /^type\s/.test(p);
        const name = p.replace(/^type\s+/, '').split(/\s+as\s+/).pop().trim();
        (isType ? t : v).add(name);
      }
    }
    for (const m of src.matchAll(/^export\s+(type\s+)?\{([^}]+)\}\s*from\s*['"]([^'"]+)['"]/gms)) {
      // re-exports from a sibling: surface them through this file's path
      for (const part of m[2].split(',')) {
        const p = part.trim();
        if (!p) continue;
        const isType = Boolean(m[1]) || /^type\s/.test(p);
        const name = p.replace(/^type\s+/, '').split(/\s+as\s+/).pop().trim();
        (isType ? t : v).add(name);
      }
    }
    for (const n of v) add(values, n, rel);
    for (const n of t) if (!v.has(n)) add(types, n, rel);
    }
  }
}

const byFile = new Map();
for (const [n, file] of values) (byFile.get(file) ?? byFile.set(file, { v: [], t: [] }).get(file)).v.push(n);
for (const [n, file] of types) (byFile.get(file) ?? byFile.set(file, { v: [], t: [] }).get(file)).t.push(n);
for (const [file, { v, t }] of [...byFile].sort(([a], [b]) => a.localeCompare(b))) {
  if (v.length) lines.push(`export { ${v.sort().join(', ')} } from '${file}';`);
  if (t.length) lines.push(`export type { ${t.sort().join(', ')} } from '${file}';`);
}
const body = `// GENERATED by scripts/dev/gen-index.mjs. Do not edit by hand; run \`node scripts/dev/gen-index.mjs\`.\n${lines.join('\n')}\nexport * from './mui';\n`;
writeFileSync(join(root, 'index.ts'), body);
console.log(`${values.size} values, ${types.size} types from ${byFile.size} files`);
if (clashes.length) console.log('CLASHES:\n' + clashes.join('\n'));

