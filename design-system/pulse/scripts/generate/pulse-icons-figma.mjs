/**
 * Decodes Figma vector geometry (commandsBlob in msg.blobs) for custom icons the npm package lacks.
 *   node --max-old-space-size=8192 scripts/generate/pulse-icons-figma.mjs
 * Writes src/icons/figmaExtra.tsx (Dash, Split, Gateway, Cancel, ProjectLifecycle).
 */
import { writeFileSync } from 'node:fs';
import { loadFig, gid } from '../figma/fig-load.mjs';

const { msg, nodes, children, pages } = await loadFig('pulse 2.0.fig');
const page = pages.find((p) => p.name.trim().endsWith('Icons'));
const want = { Dash: 'Dash', Split: 'Split', Gateway: 'Gateway', Cancel: 'Cancel', 'project-lifecycle': 'ProjectLifecycle' };

function decode(bytes) {
  const dv = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  let o = 0, d = '';
  const f = () => { const v = dv.getFloat32(o, true); o += 4; return +v.toFixed(4); };
  while (o < bytes.length) {
    const c = bytes[o++];
    if (c === 0) d += 'Z';
    else if (c === 1) d += `M${f()} ${f()}`;
    else if (c === 2) d += `L${f()} ${f()}`;
    else if (c === 3) d += `Q${f()} ${f()} ${f()} ${f()}`;
    else if (c === 4) d += `C${f()} ${f()} ${f()} ${f()} ${f()} ${f()}`;
    else break;
  }
  return d;
}
const cssColor = (p) => (p && p.type === 'SOLID' && p.visible !== false ? `rgb(${Math.round(p.color.r * 255)},${Math.round(p.color.g * 255)},${Math.round(p.color.b * 255)})` : null);

function collect(n, ox, oy, out) {
  if (n.visible === false) return;
  const x = ox + (n.transform?.m02 ?? 0), y = oy + (n.transform?.m12 ?? 0);
  const geoms = [...(n.fillGeometry ?? []).map((g) => ['fill', g]), ...(n.strokeGeometry ?? []).map((g) => ['stroke', g])];
  // strokeGeometry is already an outlined shape, so it is always painted as a fill.
  for (const [kind, g] of geoms) {
    const bytes = msg.blobs[g.commandsBlob]?.bytes;
    if (!bytes) continue;
    // apply node translation (no rotation handling beyond translation; checked visually)
    const t = n.transform ?? { m00: 1, m01: 0, m02: 0, m10: 0, m11: 1, m12: 0 };
    const d = decode(bytes);
    const paint = kind === 'fill' ? n.fillPaints?.[0] : n.strokePaints?.[0];
    out.push({ d, fill: cssColor(paint) ? 'currentColor' : 'currentColor', rule: g.windingRule === 'ODD' ? 'evenodd' : 'nonzero', t: [t.m00, t.m10, t.m01, t.m11, x, y], rot: n.transform });
  }
  for (const c of children.get(gid(n.guid)) ?? []) collect(c, x, y, out);
}

const res = [];
const tops = [];
const walk = (n) => { for (const c of children.get(gid(n.guid)) ?? []) { if (c.type === 'SYMBOL' && want[c.name?.trim()]) tops.push(c); else walk(c); } };
walk(page);
for (const top of tops) {
  const key = want[top.name?.trim()];
  const out = [];
  for (const c of children.get(gid(top.guid)) ?? []) collect(c, 0, 0, out);
  const w = Math.round(top.size?.x ?? 24), h = Math.round(top.size?.y ?? 24);
  res.push({ key, w, h, out });
  console.log(key, w, h, out.length, 'paths');
}
const src = res.map(({ key, w, h, out }) => {
  const nodesJson = out.map((p) => `["path",{"d":${JSON.stringify(p.d)},"fill":"currentColor","fillRule":"${p.rule}"${p.t[0] === 1 && p.t[3] === 1 && p.t[1] === 0 && p.t[2] === 0 ? `,"transform":"translate(${p.t[4]} ${p.t[5]})"` : `,"transform":"matrix(${p.t.join(' ')})"`}}]`);
  return `export const ${key}Icon = /*#__PURE__*/ createPulseIcon(${JSON.stringify(key + 'Icon')}, "0 0 ${w} ${h}", ${w}, ${h}, [${nodesJson.join(',')}] as IconNode[], true);`;
}).join('\n');
writeFileSync(new URL('../../src/icons/figmaExtra.tsx', import.meta.url), `/* eslint-disable */\n// GENERATED by scripts/generate/pulse-icons-figma.mjs from Figma vector geometry.\nimport { createPulseIcon } from './createPulseIcon';\nimport type { IconNode } from './createPulseIcon';\n\n${src}\n`);
