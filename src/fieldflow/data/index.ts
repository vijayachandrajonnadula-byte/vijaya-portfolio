const today = new Date();
const todayStr = (h: number, m = 0) => {
  const d = new Date(today);
  d.setHours(h, m, 0, 0);
  return d.toISOString();
};
const tomorrowStr = (h: number, m = 0) => {
  const d = new Date(today);
  d.setDate(d.getDate() + 1);
  d.setHours(h, m, 0, 0);
  return d.toISOString();
};
const yesterdayStr = (h: number, m = 0) => {
  const d = new Date(today);
  d.setDate(d.getDate() - 1);
  d.setHours(h, m, 0, 0);
  return d.toISOString();
};

